using System;
using UnityEngine;

namespace Gallop.Live.Rendering
{
    // Viewer preview policy: explicit authored channels and base-camera resolver.
    // A missing left channel is explicitly transparent, never an inferred track.
    public sealed class OriginalLiveContinuousRenderer : IDisposable
    {
        readonly OriginalLiveContinuousProvider provider;
        readonly OriginalCameraProducer cameras;
        readonly OriginalMaskCoverageGenerator coverage;
        readonly OriginalMultiCameraRenderer renderer;
        readonly Func<OriginalLiveTimelineBridge.Frame, Camera> selectBaseCamera;
        readonly RenderTexture output;
        readonly int rightTrack;
        readonly int? leftTrack;
        bool disposed, rendering;
        public int RenderCount { get; private set; }
        public string LastStatus { get; private set; } = "NotRendered";
        public Exception LastException { get; private set; }
        public OriginalCompositeCueAdapter.Unresolved LastUnresolved { get; private set; }

        // This mapping describes textures generated by this Viewer preview at a
        // full viewport with no mip chain. It is not original-game TextureMapping.
        public static OriginalCompositeCueAdapter.TextureMapping FullViewportMapping(int height)
        {
            if (height <= 0) throw new ArgumentOutOfRangeException(nameof(height));
            var identity = new Vector4(1, 1, 0, 0);
            return new OriginalCompositeCueAdapter.TextureMapping(identity, 1f / height, identity, 0);
        }

        public OriginalLiveContinuousRenderer(OriginalLiveContinuousProvider provider,
            int rightTrack, int? leftTrack, Func<OriginalLiveTimelineBridge.Frame, Camera> selectBaseCamera,
            Shader compositeShader, Shader coverageShader, RenderTexture output)
        {
            if (provider == null || selectBaseCamera == null || !output || !output.IsCreated())
                throw new ArgumentException("Provider, explicit camera resolver and created target are required.");
            if (rightTrack < 0 || leftTrack == rightTrack || leftTrack < 0)
                throw new ArgumentException("Distinct nonnegative authored channels are required.");
            this.provider = provider; this.rightTrack = rightTrack; this.leftTrack = leftTrack;
            this.selectBaseCamera = selectBaseCamera; this.output = output;
            try
            {
                cameras = new OriginalCameraProducer(output.width, output.height);
                coverage = new OriginalMaskCoverageGenerator(coverageShader);
                renderer = new OriginalMultiCameraRenderer(compositeShader, RenderTextureFormat.ARGBFloat);
            }
            catch { cameras?.Dispose(); coverage?.Dispose(); renderer?.Dispose(); throw; }
            provider.FrameReady += OnFrame;
        }

        bool Find(OriginalLiveContinuousProvider.Frame frame, int track,
            out OriginalLiveContinuousProvider.ResolvedSelection result)
        {
            result = default; int count = 0;
            foreach (var selection in frame.Selections)
                if (selection.Selection.TrackOrdinal == track) { result = selection; count++; }
            return count == 1;
        }
        void OnFrame(OriginalLiveContinuousProvider.Frame frame)
        {
            if (disposed || rendering) return;
            LastException = null; LastUnresolved = OriginalCompositeCueAdapter.Unresolved.None;
            if (!Find(frame, rightTrack, out var right)) { LastStatus = "MissingTrackSelection"; return; }
            var left = default(OriginalLiveContinuousProvider.ResolvedSelection);
            if (leftTrack.HasValue && !Find(frame, leftTrack.Value, out left)) { LastStatus = "MissingTrackSelection"; return; }
            bool ready = right.Snapshot.TryCreatePass0Parameters(out var rp, out var ru);
            var lp = default(OriginalMaskCoverageGenerator.Parameters);
            var lu = OriginalCompositeCueAdapter.Unresolved.None;
            if (leftTrack.HasValue) ready = left.Snapshot.TryCreatePass0Parameters(out lp, out lu) && ready;
            LastUnresolved = ru | lu;
            if (!ready) { LastStatus = "UnresolvedDrawInputs"; return; }
            var baseCamera = selectBaseCamera(frame.Selected);
            if (!baseCamera || !right.Selection.ViewerCamera || (leftTrack.HasValue && !left.Selection.ViewerCamera))
            { LastStatus = "MissingSelectedCamera"; return; }
            var full = new Rect(0, 0, 1, 1);
            if (right.Selection.ViewerCamera.rect != full || (leftTrack.HasValue && left.Selection.ViewerCamera.rect != full))
            { LastStatus = "UnsupportedViewerViewport"; return; }
            rendering = true;
            try
            {
                var background = cameras.RenderBase(baseCamera);
                renderer.RenderSequential(background,
                    () => coverage.GenerateSubmission(cameras.RenderInput(right.Selection.ViewerCamera), output.width, output.height, rp),
                    () => leftTrack.HasValue
                        ? coverage.GenerateSubmission(cameras.RenderInput(left.Selection.ViewerCamera), output.width, output.height, lp)
                        : new OriginalMultiCameraRenderer.Submission(Texture2D.blackTexture,
                            OriginalMultiCameraRenderer.InputEncoding.StraightColorWithCoverage, 0), output);
                RenderCount++; LastStatus = "RenderedContinuousViewerCameras";
            }
            catch (Exception e) { LastException = e; LastStatus = "RenderFailed"; }
            finally { rendering = false; }
        }
        public void Dispose()
        {
            if (disposed) return;
            if (rendering) throw new InvalidOperationException("Cannot dispose a rendering preview.");
            disposed = true; provider.FrameReady -= OnFrame;
            renderer.Dispose(); coverage.Dispose(); cameras.Dispose();
        }
    }
}
